#!/usr/bin/env node
/* dump.mjs — build the JSON the gates read, from a tree you NAME, and refuse if it came from elsewhere.
 *
 * Why this exists: the old dump builder was a checked-in entry file with absolute import paths that
 * pointed at one repo. Running it with `--alias:@=<worktree>` looked like it redirected the build and
 * did not — the entry imported the main tree by absolute path, so a "worktree dump" silently contained
 * the main tree, and every gate downstream printed a confident verdict about the wrong files. A gate
 * can only be trusted as far as the tree it actually read, so the tree is now an argument and the
 * output carries the tree it came from.
 *
 *   node dump.mjs <ww1|ww2> --repo=<tree> --out=<file.json> [--expect=id1,id2] [--forbid=id3]
 *
 * --expect is how a worktree run proves the apply is in the dump it gates; --forbid is how a run
 * proves it is gating a clean tree and not a sibling checkout.
 */
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';

const [site, ...rest] = process.argv.slice(2);
if (!['ww1', 'ww2'].includes(site)) {
  console.error('usage: dump.mjs <ww1|ww2> --repo=<tree> --out=<file.json> [--expect=id,id] [--forbid=id]');
  process.exit(2);
}
const arg = (name) => {
  const hit = rest.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : null;
};
const REPO = resolve(arg('repo') || (site === 'ww2' ? '/Users/ka-kinpoon/Project/WW2/ww2-european' : '/Users/ka-kinpoon/Project/WW2/WW1-European'));
const OUT = arg('out');
const EXPECT = (arg('expect') || '').split(',').filter(Boolean);
const FORBID = (arg('forbid') || '').split(',').filter(Boolean);
if (!OUT) { console.error('dump.mjs: --out=<file.json> is required, so no run can quietly overwrite the wrong dump'); process.exit(2); }
if (!existsSync(join(REPO, 'lib', 'data', 'index.ts'))) {
  console.error(`dump.mjs: ${REPO} has no lib/data/index.ts — that is not one of the two app trees`);
  process.exit(2);
}

/* WW1 declares its curated links in campaign-events.ts but the old entry never exported them, so a
 * dump there reported 0 links and every WW1 link verdict came from a file the dump could not see. The
 * export name is read from the repo rather than assumed; absent means absent, and the count printed at
 * the end makes a silent zero visible. */
const linksFile = join(REPO, 'lib', 'data', 'campaign-events.ts');
const linksSrc = existsSync(linksFile) ? readFileSync(linksFile, 'utf8') : '';
const linksName = (linksSrc.match(/export const (\w*LINKS\w*)/) || [])[1] || '';
const links = linksName
  ? `import { ${linksName} as CAMPAIGN_EVENT_LINKS } from '${REPO}/lib/data/campaign-events';`
  : `const CAMPAIGN_EVENT_LINKS: never[] = [];`;
if (!linksName) console.error(`dump.mjs: ${linksFile} exports no *LINKS* array — the dump will carry 0 links`);
const march = site === 'ww1' ? 'MARCH_LINES,' : '';

const entry = join(tmpdir(), `dump-entry-${site}.ts`);
writeFileSync(entry, `/* generated by dump.mjs for ${REPO} — do not edit, it is rewritten on every run */
${links}
import {
  EVENTS, FIGURES, CAMPAIGN_LINES, ${march} SOURCES, UNCERTAINTIES, COUNTRY_STATS, STATUS_ORDER,
} from '${REPO}/lib/data/index';
import { TURNING_POINTS } from '${REPO}/lib/data/turning-points';
import { PLACES } from '${REPO}/lib/data/places';
import { MONTHS } from '${REPO}/lib/site';

const __SOURCE_REPO = ${JSON.stringify(REPO)};
console.log(JSON.stringify({
  __SOURCE_REPO,
  EVENTS, FIGURES, CAMPAIGN_LINES, MARCH_LINES: ${site === 'ww1' ? 'MARCH_LINES' : '[]'},
  SOURCES, UNCERTAINTIES, COUNTRY_STATS, STATUS_ORDER, TURNING_POINTS, PLACES, CAMPAIGN_EVENT_LINKS,
  MONTHS,
}));
`);

const bundle = join(tmpdir(), `dump-${site}.mjs`);
execFileSync('npx', ['--no-install', 'esbuild', entry, '--bundle', '--platform=node', '--format=esm',
  `--outfile=${bundle}`, `--alias:@=${REPO}`, '--log-level=error'], { cwd: REPO, stdio: 'inherit' });

const text = execFileSync(process.execPath, [bundle], { maxBuffer: 1 << 28, encoding: 'utf8' });
const dump = JSON.parse(text);

/* The proof, not the intention: the bundle says which tree it imported. */
if (dump.__SOURCE_REPO !== REPO) {
  console.error(`dump.mjs: the bundle reports it read ${dump.__SOURCE_REPO}, not ${REPO} — refusing to write ${OUT}`);
  process.exit(2);
}
const ids = [...dump.CAMPAIGN_LINES, ...dump.MARCH_LINES].map((l) => l.id);
const eids = dump.EVENTS.map((e) => e.id);
const missing = EXPECT.filter((id) => !ids.includes(id) && !eids.includes(id));
const present = FORBID.filter((id) => ids.includes(id) || eids.includes(id));
if (missing.length) { console.error(`dump.mjs: ${REPO} does NOT contain ${missing.join(', ')} — the apply is not in the tree you named`); process.exit(2); }
if (present.length) { console.error(`dump.mjs: ${REPO} contains ${present.join(', ')}, which --forbid says it must not — wrong tree?`); process.exit(2); }

mkdirSync(dirname(resolve(OUT)), { recursive: true });
writeFileSync(resolve(OUT), text);
const lines = dump.CAMPAIGN_LINES.length + dump.MARCH_LINES.length;
console.log(`${site}: ${dump.EVENTS.length} events, ${lines} lines, ${dump.CAMPAIGN_EVENT_LINKS.length} links, ` +
  `${dump.SOURCES.length} sources, ${dump.UNCERTAINTIES.length} uncertainties, ${dump.MONTHS.length} months ` +
  `— read from ${REPO}${EXPECT.length ? `, all ${EXPECT.length} expected id(s) present` : ''}`);
